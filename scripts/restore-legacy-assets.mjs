import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, join } from 'node:path';

// Restore observed image URLs without duplicating the image payload in dist.
// Content hashes select the exact emitted original, not a similarly named logo
// or a thumbnail. Rebuilds regenerate rules when Astro's asset names change.
const root = process.cwd();
const dist = resolve(root, 'dist');
const assets = join(dist, '_astro');
const inventory = JSON.parse(readFileSync(join(root, 'src/data/legacy-assets.json'), 'utf8'));
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const emitted = new Map();
for (const file of readdirSync(assets).sort()) {
  if (!/\.(avif|svg)$/.test(file)) continue;
  emitted.set(digest(readFileSync(join(assets, file))), file);
}
const rules = [];
for (const [legacyPath, sourceName] of Object.entries(inventory)) {
  if (!/^\/elan-client-logos\/[A-Za-z0-9-]+\.(avif|webp|png)$/.test(legacyPath)
    || !/^[A-Za-z0-9-]+\.avif$/.test(sourceName)) throw new Error(`Unsafe legacy asset path: ${legacyPath}`);
  const source = join(root, 'src/assets/client-logos', sourceName);
  if (!existsSync(source)) throw new Error(`Missing source for ${legacyPath}`);
  const target = emitted.get(digest(readFileSync(source)));
  if (!target) throw new Error(`No exact emitted asset found for ${legacyPath}`);
  const pattern = legacyPath.slice(1).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  rules.push(`RewriteRule ^${pattern}$ /_astro/${target} [R=301,L]`);
}
const file = join(dist, '.htaccess');
const htaccess = readFileSync(file, 'utf8');
const block = /# BEGIN LEGACY CLIENT ASSETS[\s\S]*?# END LEGACY CLIENT ASSETS/;
if (!block.test(htaccess)) throw new Error('Missing legacy asset rule marker in .htaccess');
if (process.argv.includes('--check')) {
  for (const rule of rules) if (!htaccess.includes(rule)) throw new Error(`Missing legacy asset rule: ${rule}`);
  console.log(`Legacy asset audit passed: ${rules.length} exact image destinations verified.`);
} else {
  writeFileSync(file, htaccess.replace(block, `# BEGIN LEGACY CLIENT ASSETS\n# Generated by scripts/restore-legacy-assets.mjs; deploy dist/.htaccess.\n${rules.join('\n')}\n# END LEGACY CLIENT ASSETS`));
  console.log(`Restored ${rules.length} legacy image URLs without duplicate image files.`);
}
